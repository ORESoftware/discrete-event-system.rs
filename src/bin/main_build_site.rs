fn main() -> anyhow::Result<()> {
    let output = env::args()
        .nth(1)
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("out/rust-animation-demo.html"));
    write_parent_dirs(&output)?;
    let html = build_html(&sample_animation())?;
    fs::write(&output, html)?;
    eprintln!("HTML simulation written: {}", output.display());
    Ok(())
}

fn write_parent_dirs(path: &Path) -> anyhow::Result<()> {
    if let Some(parent) = path
        .parent()
        .filter(|parent| !parent.as_os_str().is_empty())
    {
        fs::create_dir_all(parent)?;
    }
    Ok(())
}

